// Preview endpoint handler - returns rendered HTML without sending email
async function handlePreview(req: Request): Promise<Response> {
  const previewCorsHeaders = {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Headers': 'authorization, content-type',
  }

  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: previewCorsHeaders })
  }

  const apiKey = Deno.env.get('LOVABLE_API_KEY')
  const authHeader = req.headers.get('Authorization')

  if (!apiKey || authHeader !== `Bearer ${apiKey}`) {
    return new Response(JSON.stringify({ error: 'Unauthorized' }), {
      status: 401,
      headers: { ...previewCorsHeaders, 'Content-Type': 'application/json' },
    })
  }

  let type: string
  try {
    const body = await req.json()
    type = body.type
  } catch (error) {
    return new Response(JSON.stringify({ error: 'Invalid JSON in request body' }), {
      status: 400,
      headers: { ...previewCorsHeaders, 'Content-Type': 'application/json' },
    })
  }

  const EmailTemplate = EMAIL_TEMPLATES[type]

  if (!EmailTemplate) {
    return new Response(JSON.stringify({ error: `Unknown email type: ${type}` }), {
      status: 400,
      headers: { ...previewCorsHeaders, 'Content-Type': 'application/json' },
    })
  }

  const sampleData = SAMPLE_DATA[type] || {}
  const html = await renderAsync(React.createElement(EmailTemplate, sampleData))

  return new Response(html, {
    status: 200,
    headers: { ...previewCorsHeaders, 'Content-Type': 'text/html; charset=utf-8' },
  })
}

/** Always-log helper so we have a paper trail in email_send_log no matter
 *  where in the pipeline a failure happens (rendering, signature check,
 *  template missing, enqueue). The caller doesn't have to remember to log
 *  on every error path. */
async function recordEmailFailure(
  template: string | null,
  recipient: string | null,
  reason: string,
): Promise<void> {
  try {
    const supabase = createClient(
      Deno.env.get('SUPABASE_URL')!,
      Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!,
    )
    await supabase.from('email_send_log').insert({
      message_id: crypto.randomUUID(),
      template_name: template || 'unknown',
      recipient_email: recipient || 'unknown',
      status: 'failed',
      error_message: reason.slice(0, 500),
    })
  } catch (logErr) {
    console.error('email_send_log insert failed', { reason, logErr })
  }
}

// Webhook handler - verifies signature and sends email
async function handleWebhook(req: Request): Promise<Response> {
  const apiKey = Deno.env.get('LOVABLE_API_KEY')
  const supabaseUrl = Deno.env.get('SUPABASE_URL')
  const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')

  // Sanity-check every required env var FIRST and log specifically which one
  // is missing. Previously a missing var produced a generic 500 and the admin
  // had to dig through deno logs to figure out why no emails were sending.
  const missingVars = [
    !apiKey && 'LOVABLE_API_KEY',
    !supabaseUrl && 'SUPABASE_URL',
    !serviceKey && 'SUPABASE_SERVICE_ROLE_KEY',
  ].filter(Boolean)
  if (missingVars.length > 0) {
    const reason = `Missing required env vars: ${missingVars.join(', ')}`
    console.error('[auth-email-hook] ' + reason)
    await recordEmailFailure(null, null, reason)
    return new Response(
      JSON.stringify({ error: 'Server configuration error', missing: missingVars }),
      { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  }

  // Verify signature + timestamp, then parse payload.
  let payload: any
  let run_id = ''
  try {
    const verified = await verifyWebhookRequest({
      req,
      secret: apiKey,
      parser: parseEmailWebhookPayload,
    })
    payload = verified.payload
    run_id = payload.run_id
  } catch (error) {
    if (error instanceof WebhookError) {
      switch (error.code) {
        case 'invalid_signature':
        case 'missing_timestamp':
        case 'invalid_timestamp':
        case 'stale_timestamp':
          console.error('Invalid webhook signature', { error: error.message })
          return new Response(JSON.stringify({ error: 'Invalid signature' }), {
            status: 401,
            headers: { ...corsHeaders, 'Content-Type': 'application/json' },
          })
        case 'invalid_payload':
        case 'invalid_json':
          console.error('Invalid webhook payload', { error: error.message })
          return new Response(
            JSON.stringify({ error: 'Invalid webhook payload' }),
            { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
          )
      }
    }

    console.error('Webhook verification failed', { error })
    return new Response(
      JSON.stringify({ error: 'Invalid webhook payload' }),
      { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  }

  if (!run_id) {
    console.error('Webhook payload missing run_id')
    return new Response(
      JSON.stringify({ error: 'Invalid webhook payload' }),
      {
        status: 400,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      }
    )
  }

  if (payload.version !== '1') {
    console.error('Unsupported payload version', { version: payload.version, run_id })
    return new Response(
      JSON.stringify({ error: `Unsupported payload version: ${payload.version}` }),
      {
        status: 400,
        headers: { ...corsHeaders, 'Content-Type': 'application/json' },
      }
    )
  }

  // The email action type is in payload.data.action_type (e.g., "signup", "recovery")
  // payload.type is the hook event type ("auth")
  const emailType = payload.data.action_type
  console.log('Received auth event', { emailType, email: payload.data.email, run_id })

  const EmailTemplate = EMAIL_TEMPLATES[emailType]
  if (!EmailTemplate) {
    console.error('Unknown email type', { emailType, run_id })
    return new Response(
      JSON.stringify({ error: `Unknown email type: ${emailType}` }),
      { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  }

  // Build template props from payload.data (HookData structure)
  const templateProps = {
    siteName: SITE_NAME,
    siteUrl: `https://${ROOT_DOMAIN}`,
    recipient: payload.data.email,
    confirmationUrl: payload.data.url,
    token: payload.data.token,
    email: payload.data.email,
    newEmail: payload.data.new_email,
  }

  // Render React Email to HTML and plain text. A template bug used to
  // surface as a generic 500 with no row in email_send_log — now we
  // always record the failure with the actual error so the admin can see
  // exactly which template threw.
  let html: string
  let text: string
  try {
    html = await renderAsync(React.createElement(EmailTemplate, templateProps))
    text = await renderAsync(React.createElement(EmailTemplate, templateProps), {
      plainText: true,
    })
  } catch (renderErr) {
    const reason = `Template render failed (${emailType}): ${
      (renderErr as Error)?.message || String(renderErr)
    }`
    console.error('[auth-email-hook] ' + reason, { run_id })
    await recordEmailFailure(emailType, payload.data.email, reason)
    return new Response(
      JSON.stringify({ error: reason }),
      { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  }

  // Enqueue email for async processing by the dispatcher (process-email-queue).
  const supabase = createClient(
    Deno.env.get('SUPABASE_URL')!,
    Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!
  )

  const messageId = crypto.randomUUID()

  // Log pending BEFORE enqueue so we have a record even if enqueue crashes
  await supabase.from('email_send_log').insert({
    message_id: messageId,
    template_name: emailType,
    recipient_email: payload.data.email,
    status: 'pending',
  })

  const { error: enqueueError } = await supabase.rpc('enqueue_email', {
    queue_name: 'auth_emails',
    payload: {
      run_id,
      message_id: messageId,
      to: payload.data.email,
      from: `${SITE_NAME} <noreply@${FROM_DOMAIN}>`,
      sender_domain: SENDER_DOMAIN,
      subject: EMAIL_SUBJECTS[emailType] || 'Notification',
      html,
      text,
      purpose: 'transactional',
      label: emailType,
      queued_at: new Date().toISOString(),
    },
  })

  if (enqueueError) {
    console.error('Failed to enqueue auth email', { error: enqueueError, run_id, emailType })
    await supabase.from('email_send_log').insert({
      message_id: messageId,
      template_name: emailType,
      recipient_email: payload.data.email,
      status: 'failed',
      error_message: 'Failed to enqueue email',
    })
    return new Response(JSON.stringify({ error: 'Failed to enqueue email' }), {
      status: 500,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    })
  }

  console.log('[auth-email-hook] Enqueued', { emailType, email: payload.data.email, run_id })

  // ── Self-kick the queue dispatcher ──
  // The architecture relies on pg_cron calling process-email-queue every 5s
  // to drain the queue. If that cron job has been removed / disabled (which
  // is what was happening to this user — auth emails were enqueued but never
  // sent), every confirmation email silently disappears at TTL expiry.
  //
  // To make signup robust against a broken cron, fire-and-forget invoke the
  // dispatcher right after enqueue. This is idempotent — process-email-queue
  // is safe to call concurrently and will just no-op if the cron is also
  // running. We don't await it because we don't want to block the auth
  // webhook on email delivery; if the dispatcher crashes the queue still
  // holds the message for the next cron tick (assuming cron exists) or the
  // next signup's self-kick.
  try {
    const dispatchUrl = `${supabaseUrl}/functions/v1/process-email-queue`
    void fetch(dispatchUrl, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${serviceKey}`,
        'Content-Type': 'application/json',
      },
      // No body — the dispatcher reads its own state.
    }).catch((kickErr) => {
      console.warn('[auth-email-hook] dispatcher kick failed (queue cron should still drain):', kickErr)
    })
  } catch (kickErr) {
    console.warn('[auth-email-hook] dispatcher kick threw:', kickErr)
  }

  return new Response(
    JSON.stringify({ success: true, queued: true }),
    { status: 200, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
  )
}

Deno.serve(async (req) => {
  const url = new URL(req.url)

  // Handle CORS preflight for main endpoint
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders })
  }

  // Route to preview handler for /preview path
  if (url.pathname.endsWith('/preview')) {
    return handlePreview(req)
  }

  // Main webhook handler. Top-level catch logs an email_send_log row even
  // for unexpected failures (so an admin can always see WHY a confirmation
  // email didn't arrive, even when an exception bubbled out of handleWebhook
  // before it could log itself).
  try {
    return await handleWebhook(req)
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Unknown error'
    console.error('[auth-email-hook] handler exception:', message)
    await recordEmailFailure(null, null, `Unhandled hook exception: ${message}`)
    return new Response(JSON.stringify({ error: message }), {
      status: 500,
      headers: { ...corsHeaders, 'Content-Type': 'application/json' },
    })
  }
})
